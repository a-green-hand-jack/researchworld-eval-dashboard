def load_e1(pattern="main*_*.csv"):
    fs = sorted(glob.glob(os.path.join(EXP, "results", "e1", pattern)))
    fs = [f for f in fs if not f.endswith("_ident.csv")]
    # one file per configuration: the 200-replicate run (main200_*) supersedes the 100-replicate pilot (main_*)
    stem = lambda f: os.path.basename(f).replace("main200_", "").replace("main_", "")
    best = {}
    for f in fs:
        k = stem(f)
        if k not in best or "main200_" in f:
            best[k] = f
    fs = sorted(best.values())
    if not fs:
        raise SystemExit("no E1 result files found under " + EXP)
    d = pd.concat([pd.read_csv(f).assign(file=os.path.basename(f)) for f in fs], ignore_index=True)
    sv = d.method.map(split_method)
    d["score"], d["variant"] = sv.map(lambda t: t[0]), sv.map(lambda t: t[1])
    return d


def mean_ci(x, level=0.95):
    """t-interval for the mean over independent replicates (rows with NaN dropped); returns mean, lo, hi, n."""
    x = np.asarray(x, float)
    x = x[np.isfinite(x)]
    n = len(x)
    if n < 2:
        return (x.mean() if n else np.nan), np.nan, np.nan, n
    m, se = x.mean(), x.std(ddof=1) / np.sqrt(n)
    h = stats.t.ppf(0.5 + level / 2, n - 1) * se
    return m, m - h, m + h, n


def agg(d, col, by=("method", "score", "variant")):
    rows = []
    for k, g in d.groupby(list(by), sort=False):
        m, lo, hi, n = mean_ci(g[col])
        rows.append(dict(zip(by, k if isinstance(k, tuple) else (k,)), mean=m, lo=lo, hi=hi, n=n))
    return pd.DataFrame(rows)


def provenance():
    try:
        sha = subprocess.check_output(["git", "-C", EXP, "rev-parse", "HEAD"], text=True).strip()
    except Exception:
        sha = "unknown"
    return sha


def save(fig, name):
    os.makedirs(FIG, exist_ok=True)
    p = os.path.join(FIG, name)
    fig.savefig(p)
    plt.close(fig)
    print("wrote", p, "| experiment-repo", provenance())
    return p


def cfg_label(r):
    return f"{r['family']}, D={int(r['D'])}, {'het.' if r['hetero'] else 'hom.'}, {r['pred']}"


def pm(m, lo, hi, nd=3):
    """'mean ± halfwidth' for a table cell."""
    if not np.isfinite(m):
        return "--"
    h = (hi - lo) / 2 if np.isfinite(lo) else np.nan
    return f"{m:.{nd}f}" + (f" $\\pm$ {h:.{nd}f}" if np.isfinite(h) else "")


def write_table(tex, name):
    os.makedirs(TAB, exist_ok=True)
    p = os.path.join(TAB, name)
    open(p, "w").write(f"% generated by figtab; experiment-repo {provenance()}\n" + tex)
    print("wrote", p)


