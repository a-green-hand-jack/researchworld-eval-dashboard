#!/usr/bin/env python3
"""Render committed score-intervention results; never runs an optimizer."""
import argparse
import hashlib
import json
import platform
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.ticker import PercentFormatter
import numpy as np
import pandas as pd

RULES = ['mean', 'median', 'geometric', 'minimum', 'borda']
LABELS = dict(zip(RULES, ['Mean', 'Median', 'Geometric', 'Minimum', 'Borda']))
COLORS = dict(zip(RULES, ['#0072B2', '#D55E00', '#009E73', '#CC79A7', '#333333']))
STYLES = dict(zip(RULES, ['-', '--', '-.', ':', (0, (5, 2, 1, 2))]))
NAMES = {'helm': 'HELM MMLU', 'open_llm': 'Open LLM'}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def primary(d):
    return d[(d.ceiling == 'unit') & (d.alpha == 1) & (~d.strict)]


def latex_table(header, rows, alignment):
    return ('% Generated by presentation/render.py; do not edit numerical entries.\n'
            + '\\begin{tabular}{' + alignment + '}\n\\toprule\n'
            + ' & '.join(header) + ' \\\\\n\\midrule\n'
            + ''.join(' & '.join(map(str, row)) + ' \\\\\n' for row in rows)
            + '\\bottomrule\n\\end{tabular}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--analysis-root', type=Path, required=True)
    parser.add_argument('--output-root', type=Path, default=Path('.'))
    parser.add_argument('--width', type=float, default=5.5, help='Full text width in inches')
    args = parser.parse_args()
    src, out = args.analysis_root.resolve(), args.output_root.resolve()
    for p in ['figures', 'tables', 'presentation']:
        (out/p).mkdir(parents=True, exist_ok=True)
    used = {}
    output_map = {}
    def read(path):
        used[path] = sha(src/path)
        return pd.read_csv(src/path)
    def savefig(fig, stem, inputs):
        fig.canvas.draw()
        bbox = fig.get_tightbbox(fig.canvas.get_renderer())
        width, height = fig.get_size_inches()
        assert bbox.x0 >= 0 and bbox.y0 >= 0 and bbox.x1 <= width and bbox.y1 <= height, f'Clipped artwork in {stem}: {bbox}'
        for suffix in ['pdf', 'png']:
            path = f'figures/{stem}.{suffix}'
            kw = {'metadata': {'CreationDate': None, 'ModDate': None}} if suffix == 'pdf' else {}
            fig.savefig(out/path, dpi=200, **kw)
            output_map[path] = {'inputs': inputs, 'sha256': sha(out/path)}
        plt.close(fig)
    def table(stem, header, rows, align, inputs):
        path = f'tables/{stem}.tex'
        (out/path).write_text(latex_table(header, rows, align))
        output_map[path] = {'inputs': inputs, 'sha256': sha(out/path)}
        pd.DataFrame(rows, columns=header).to_csv(out/f'tables/{stem}.csv', index=False)
        output_map[f'tables/{stem}.csv'] = {'inputs': inputs, 'sha256': sha(out/f'tables/{stem}.csv')}

    plt.rcParams.update({'font.size': 8, 'axes.labelsize': 8, 'axes.titlesize': 9,
                         'legend.fontsize': 8, 'xtick.labelsize': 8, 'ytick.labelsize': 8,
                         'font.family': 'DejaVu Sans', 'pdf.fonttype': 42,
                         'axes.spines.top': False, 'axes.spines.right': False,
                         'axes.linewidth': .65, 'lines.linewidth': 1.65})
    attacks = {ds: read(f'results/attacks_{ds}.csv') for ds in NAMES}
    summary = read('results/summary.csv')
    challenger = read('results/challenger_summary.csv')
    challenger_curves = read('results/challenger_budget_curves.csv')
    pairs = read('results/challenger_paired_rules.csv')
    composition = {ds: read(f'results/composition_{ds}.csv') for ds in NAMES}
    random_mc = read('results/random_baseline_aggregate_uncertainty.csv')
    for p in ['data/manifest.json', 'data/processed/audit.json']:
        used[p] = sha(src/p)
    audit = json.loads((src/'data/processed/audit.json').read_text())
    source = json.loads((src/'data/manifest.json').read_text())
    cohorts = {}
    cohort_records = []
    for ds, d in attacks.items():
        assert d.status.isin(['exact', 'optimal', 'enumerated', 'infeasible']).all(), 'Unresolved optimizer status'
        p = primary(d)
        assert not p.duplicated(['model', 'rule']).any()
        pivot = p.pivot(index='model', columns='rule', values='k')
        assert pivot.columns.size == 5 and pivot.notna().all().all()
        keep = pivot.index[~pivot.eq(0).any(axis=1)]
        cohorts[ds] = d[d.model.isin(keep)].copy()
        assert len(keep) == {'helm': 77, 'open_llm': 4571}[ds]
        assert (primary(cohorts[ds]).groupby('rule').size() == len(keep)).all()
        for model in keep:
            cohort_records.append({'dataset': ds, 'model': model})
    pd.DataFrame(cohort_records).to_csv(out/'presentation/fixed_challengers.csv', index=False)
    output_map['presentation/fixed_challengers.csv'] = {'inputs': [f'results/attacks_{ds}.csv' for ds in NAMES], 'sha256': sha(out/'presentation/fixed_challengers.csv')}

    fig, axs = plt.subplots(1, 2, figsize=(args.width, 2.65), sharey=True)
    for ax, (ds, d) in zip(axs, cohorts.items()):
        p = primary(d)
        n = p.model.nunique(); tasks = int(p.n_tasks.iloc[0])
        for rule in RULES:
            v = p[p.rule == rule].k.to_numpy()
            curve = primary(challenger_curves)
            curve = curve[(curve.dataset == ds) & (curve.rule == rule)].sort_values('budget')
            assert curve.n.eq(n).all() and curve.budget.tolist() == list(range(tasks+1))
            x = curve.budget.to_numpy()
            y = curve.fraction.to_numpy()
            assert np.allclose(y, [(v <= k).mean() for k in x])
            ax.step(x, y, where='post', color=COLORS[rule], linestyle=STYLES[rule], label=LABELS[rule])
        ax.axhline(.5, color='.82', lw=.7, zorder=0)
        ax.set(xlim=(0, tasks + (0.2 if tasks == 6 else 0.6)), ylim=(0, 1.025), xlabel=r'Selected tasks (budget $k$)',
               title=f'{NAMES[ds]}\n{n:,} challengers, {tasks} tasks')
        ax.set_xticks([0, 10, 20, 30, 40, 50, 57] if ds == 'helm' else range(7))
        ax.yaxis.set_major_formatter(PercentFormatter(1))
    axs[0].set_ylabel('Challengers reaching co-first')
    fig.legend(*axs[0].get_legend_handles_labels(), loc='upper center', ncol=5, frameon=False,
               bbox_to_anchor=(.5, 1.01), handlelength=2.6, columnspacing=1.4)
    fig.subplots_adjust(left=.15, right=.97, bottom=.20, top=.78, wspace=.13)
    savefig(fig, 'budget_curves', ['results/challenger_budget_curves.csv'] + [f'results/attacks_{ds}.csv' for ds in NAMES])

    gain_rows = []
    fig, axs = plt.subplots(1, 2, figsize=(args.width, 2.65), sharey=True)
    for ax, (ds, d) in zip(axs, attacks.items()):
        d = d[(d.ceiling == 'unit') & (~d.strict)]
        n = d.model.nunique()
        for rule in RULES:
            g = d[d.rule == rule]
            x, y = [], []
            for alpha, s in g.groupby('alpha'):
                assert s.model.nunique() == n and len(s) == n
                x.append(alpha); y.append(s.k.notna().mean())
                gain_rows.append({'dataset':ds, 'rule':rule, 'alpha':alpha, 'n':n, 'reachable':int(s.k.notna().sum()), 'fraction':y[-1]})
            ax.plot(x, y, marker='o', markersize=3.3, color=COLORS[rule], linestyle=STYLES[rule], label=LABELS[rule])
        ax.set(xlim=(.08, 1.02), ylim=(0, 1.025), xlabel=r'Restored headroom $\alpha$',
               title=f'{NAMES[ds]}\nFixed {n:,} evaluations')
        ax.set_xticks([.1, .25, .5, 1], ['0.10', '0.25', '0.50', '1.00'])
        ax.yaxis.set_major_formatter(PercentFormatter(1))
    axs[0].set_ylabel('Reachable with any task budget')
    fig.legend(*axs[0].get_legend_handles_labels(), loc='upper center', ncol=5, frameon=False,
               bbox_to_anchor=(.5, 1.01), handlelength=2.6, columnspacing=1.4)
    fig.subplots_adjust(left=.15, right=.97, bottom=.20, top=.78, wspace=.13)
    savefig(fig, 'gain_reachability', [f'results/attacks_{ds}.csv' for ds in NAMES])
    pd.DataFrame(gain_rows).to_csv(out/'presentation/gain_reachability_values.csv', index=False)
    output_map['presentation/gain_reachability_values.csv'] = {'inputs': [f'results/attacks_{ds}.csv' for ds in NAMES], 'sha256':sha(out/'presentation/gain_reachability_values.csv')}

    fig, axs = plt.subplots(1, 2, figsize=(args.width, 2.6), sharey=True)
    for ax, (ds, d) in zip(axs, composition.items()):
        for i, rule in enumerate(RULES):
            v = d[d.rule == rule].median_k
            lo, hi = v.min(), v.max()
            ax.plot([lo, hi], [i, i], color=COLORS[rule], lw=1)
            if ds == 'helm':
                qlo, med, qhi = v.quantile([.025, .5, .975])
                ax.plot([qlo, qhi], [i, i], color=COLORS[rule], lw=4, solid_capstyle='butt')
                ax.plot(med, i, 'o', color='white', mec=COLORS[rule], ms=4)
            else:
                vals, counts = np.unique(v, return_counts=True)
                ax.scatter(vals, np.repeat(i, len(vals)), s=16*counts, color=COLORS[rule], zorder=3)
        ax.set_yticks(range(5), [LABELS[r] for r in RULES])
        ax.set_xlabel('Median minimum selected tasks')
        ax.set_title('HELM\n200 task resamples' if ds == 'helm' else 'Open LLM\nSix task deletions')
        ax.set_xlim((0, 57) if ds == 'helm' else (0, 5.5))
        ax.set_xticks([0, 10, 20, 30, 40, 50, 57] if ds == 'helm' else range(6))
        ax.grid(axis='x', color='.9', lw=.6, zorder=0)
    axs[0].invert_yaxis()
    fig.subplots_adjust(left=.17, right=.97, bottom=.22, top=.84, wspace=.16)
    savefig(fig, 'task_composition', [f'results/composition_{ds}.csv' for ds in NAMES])

    rows=[]
    for ds in NAMES:
        a=audit[ds]
        rows.append([NAMES[ds], 'v1.13.0' if ds=='helm' else '\\texttt{9c09a7cae433}',
                     57 if ds=='helm' else 6, 79 if ds=='helm' else a['retained'],
                     len(cohorts[ds].model.unique()), '0' if ds=='helm' else '1 flagged'])
    table('cohorts', ['Snapshot', 'Version / commit prefix', 'Tasks', 'Evaluations', 'Challengers', 'Excluded'], rows, 'llrrrl', ['data/manifest.json','data/processed/audit.json']+[f'results/attacks_{ds}.csv' for ds in NAMES])
    rows=[]
    for rule in RULES:
        vals=[]
        for ds in NAMES:
            s=primary(challenger);s=s[(s.dataset==ds)&(s.rule==rule)].iloc[0]
            assert s.reachable==s.n
            vals += [f'{s.median_k_reachable:g}', f'{100*s.median_k_reachable/(57 if ds=="helm" else 6):.1f}\\%']
        rows.append([LABELS[rule]]+vals)
    table('primary_budgets', ['Rule', 'HELM $k$', 'HELM $k/57$', 'Open LLM $k$', 'Open LLM $k/6$'], rows, 'lrrrr', ['results/challenger_summary.csv'])
    rows=[]
    for ds in NAMES:
        p=primary(pairs);p=p[(p.dataset==ds)&(p.rule_a=='borda')]
        for rule in ['mean','geometric','median','minimum']:
            s=p[p.rule_b==rule].iloc[0]
            assert s.a_lower+s.same+s.a_higher==s.both_reachable==s.n_challengers
            rows.append([NAMES[ds], LABELS[rule], s.n_challengers, s.a_lower, s.same, s.a_higher])
    table('paired_borda', ['Snapshot', 'Compared rule', '$N$', 'Borda cheaper', 'Equal', 'Borda costlier'], rows, 'llrrrr', ['results/challenger_paired_rules.csv'])
    rows=[]
    for rule in RULES:
        h=composition['helm'].query('rule == @rule').median_k
        o=composition['open_llm'].query('rule == @rule').median_k
        q=h.quantile([.025,.975]).tolist()
        raw=primary(summary);raw=raw[(raw.dataset=='open_llm_raw')&(raw.rule==rule)].iloc[0].median_k_reachable
        unique=primary(summary);unique=unique[(unique.dataset=='open_llm_unique')&(unique.rule==rule)].iloc[0].median_k_reachable
        rows.append([LABELS[rule], f'{h.min():g}--{h.max():g}', f'{q[0]:g}--{q[1]:g}', f'{o.min():g}--{o.max():g}', f'{raw:g}', f'{unique:g}'])
    table('robustness', ['Rule', 'HELM range', 'HELM central 95\\%', 'Open deletions', 'Open raw', 'Open unique'], rows, 'lrrrrr', ['results/composition_helm.csv','results/composition_open_llm.csv','results/summary.csv'])
    rows=[]
    for ds in NAMES:
        for rule in RULES:
            s=summary[(summary.dataset==ds)&(summary.rule==rule)&(summary.ceiling=='unit')&(summary.alpha==1)&(~summary.strict)].iloc[0]
            interval='Exact'
            if ds=='helm':
                r=random_mc[(random_mc.dataset==ds)&(random_mc.rule==rule)&(random_mc.ceiling=='unit')&(random_mc.alpha==1)&(random_mc.cohort=='full_cohort')].iloc[0]
                assert r.n_targets == r.n_expectation_targets == s.n == s.random_expected_censored_k_n
                assert r.n_infeasible_exact == 0
                assert np.isclose(r.mean_random_censored_k, s.random_expected_censored_k)
                interval=f'[{r.mc_hoeffding95_low:.1f}, {r.mc_hoeffding95_high:.1f}]'
            rows.append([NAMES[ds],LABELS[rule],f'{s.mean_k_reachable:.1f}',f'{s.random_expected_censored_k:.1f}',interval])
    table('random_selection', ['Snapshot','Rule','Optimal mean','Random mean','95\\% MC interval'], rows, 'llrrr', ['results/summary.csv','results/random_baseline_aggregate_uncertainty.csv'])
    rows=[]
    for rule in RULES:
        vals=[]
        for ds in NAMES:
            s=challenger[(challenger.dataset==ds)&(challenger.rule==rule)&(challenger.alpha==1)&(~challenger.strict)]
            for ceiling in ['unit','observed']:
                r=s[s.ceiling==ceiling].iloc[0]
                assert r.reachable==r.n
                vals.append(f'{r.median_k_reachable:g}')
        rows.append([LABELS[rule]]+vals)
    table('ceiling_sensitivity', ['Rule', 'HELM unit', 'HELM observed', 'Open unit', 'Open observed'], rows, 'lrrrr', ['results/challenger_summary.csv'])
    manifest = {'generator':'presentation/render.py', 'command':'python3 presentation/render.py --analysis-root . --output-root . --width '+str(args.width),
                'source_snapshots':{k:v for k,v in source.items() if k!='files'},
                'inputs_sha256':used, 'outputs':output_map,
                'environment':{'python':platform.python_version(),'numpy':np.__version__,'pandas':pd.__version__,'matplotlib':matplotlib.__version__},
                'width_inches':args.width,
                'fixed_primary_challengers':{ds:int(d.model.nunique()) for ds,d in cohorts.items()}}
    (out/'presentation/manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Rendered {len(output_map)} assets from {len(used)} committed input files.')

if __name__ == '__main__':
    main()
