"""Exact check of the Figure 2 example (1st-order Markov chain, vocabulary {A, B, AA}).

Byte chain: P(A|A)=1-a, P(B|A)=a, P(A|B)=b, P(B|B)=1-b. Tokenizer: left-to-right merge of
"AA" (the single BPE/MPE merge). Checks, against Monte Carlo on the tokenized stream:
 1. the token-level transition labels drawn in figure_2.png;
 2. naive next-byte prediction from the greedy encoding of a prompt ending in a lone "A"
    gives P(next byte = A) = 0 (tokenization bias);
 3. marginalising the token model over valid cover encodings of the byte prompt (the
    idea.md method, steps 1-3) recovers the byte-level P(A|...A) = 1-a exactly;
 4. Algorithm 1 and Eq. (sampling)/Proposition 1 as written in paper-repo template.tex
    (Sec. 3.4-3.5) reproduce the true byte chain on random strings.
Inputs: none (the chain is the one in /initial-state/inputs/2/figure_2.png).
"""
import random, sys
a, b = 0.3, 0.4
V = ["A", "B", "AA"]

def encode(s):
    out, i = [], 0
    while i < len(s):
        if s[i:i + 2] == "AA": out.append("AA"); i += 2
        else: out.append(s[i]); i += 1
    return out

# 1. token transitions claimed in figure_2.png, after the previous token
T = {"AA": {"AA": (1 - a) ** 2, "B": a, "A": a * (1 - a)},
     "B": {"B": 1 - b, "AA": (1 - a) * b, "A": a * b},
     "A": {"B": 1.0, "AA": 0.0, "A": 0.0}}
random.seed(0)
x, s = "B", []
for _ in range(400000):
    s.append(x)
    u = random.random()
    x = ("A" if u < 1 - a else "B") if x == "A" else ("A" if u < b else "B")
toks = encode("".join(s))[:-1]  # drop last token (its merge may be cut off)
cnt = {p: {q: 0 for q in V} for p in V}
for p, q in zip(toks, toks[1:]): cnt[p][q] += 1
print("1. token transitions: claimed vs Monte Carlo")
ok1 = True
for p in V:
    n = sum(cnt[p].values())
    for q in V:
        emp = cnt[p][q] / n
        ok1 &= abs(emp - T[p][q]) < 0.01
        print(f"   P({q:2s}|{p:2s}) claimed {T[p][q]:.4f}  MC {emp:.4f}")

# 2./3. prompt "B" + "A"*m; token model T, started after token "B"
def p_tokens(seq, prev="B"):
    pr = 1.0
    for t in seq: pr *= T[prev][t]; prev = t
    return pr

def p_bytes(prefix):
    """P(byte string starts with prefix | first byte B), summing the token model over
    cover encodings: valid token sequences whose decoding covers prefix and whose last
    token is the first to cross its end."""
    total, stack = 0.0, [[]]
    while stack:
        seq = stack.pop()
        d = "".join(seq)
        if len(d) >= len(prefix):
            if d.startswith(prefix) and encode("B" + d) == ["B"] + seq:  # valid encoding
                total += p_tokens(seq)
            continue
        if prefix.startswith(d):
            stack += [seq + [t] for t in V]
    return total

print("2./3. next-byte P(A | prompt): truth vs naive greedy-encoding vs cover marginalisation")
ok = ok1
for m in range(1, 6):
    pr = "A" * m
    truth = 1 - a
    last = encode("B" + pr)[-1]
    naive = sum(T[last][t] for t in V if t.startswith("A"))  # next token starting with A
    corr = p_bytes(pr + "A") / p_bytes(pr)
    ok &= abs(corr - truth) < 1e-12
    print(f"   prompt B{pr:5s} greedy last token {last:2s}: truth {truth:.4f} naive {naive:.4f} corrected {corr:.12f}")

# 4. Algorithm 1 (backward search) and Eq. (sampling) (recursion of Proposition 1), as
#    written in paper-repo template.tex Sec. 3.4-3.5, on random byte strings after "B".
L = 2
def alg1(x):
    """Algorithm 1: cover encodings of x (string after the fixed first byte B)."""
    C = {}
    for i in range(1, min(L, len(x)) + 1):
        hist = encode("B" + x[:len(x) - i])[1:]
        for t in V:
            if t[:i] == x[len(x) - i:] and len(t) >= i:
                seq = hist + [t]
                if encode("B" + "".join(seq)) == ["B"] + seq:
                    C[tuple(seq)] = p_tokens(seq)
    return C

def step(C, x):
    """Eq. (sampling): next-byte distribution from cover(x); returns dist and cover(x b)."""
    n, Px = len(x), sum(C.values())
    canon = tuple(encode("B" + x)[1:])
    Pc = C.get(canon, 0.0)
    prev = canon[-1] if canon else "B"
    dist, nxt = {}, {}
    for bb in "AB":
        Cb = {t: p for t, p in C.items() if len("".join(t)) > n and "".join(t)[n] == bb}
        Cbar = {}
        for t in V:
            seq = canon + (t,)
            if t[0] == bb and encode("B" + "".join(seq)) == ["B"] + list(seq):
                Cbar[seq] = Pc * T[prev][t]
        dist[bb] = (sum(Cb.values()) + sum(Cbar.values())) / Px
        nxt[bb] = {**Cb, **Cbar}
    return dist, nxt

random.seed(1)
ok4 = True
worst = 0.0
for trial in range(200):
    x = "".join(random.choice("AB") for _ in range(random.randint(1, 8)))
    C = alg1(x)
    # Algorithm 1 vs brute-force Lemma 1 sum
    ok4 &= abs(sum(C.values()) - p_bytes(x)) < 1e-12
    # recursion: 6 generated bytes, compare with the true chain and with alg1 restarted
    for _ in range(6):
        dist, nxt = step(C, x)
        truth = {"A": 1 - a, "B": a} if x[-1] == "A" else {"A": b, "B": 1 - b}
        worst = max(worst, max(abs(dist[k] - truth[k]) for k in "AB"))
        bb = random.choice("AB")
        C, x = nxt[bb], x + bb
        ok4 &= set(C) == set(alg1(x)) and all(abs(C[k] - v) < 1e-12 for k, v in alg1(x).items())
ok4 &= worst < 1e-12
print(f"4. Algorithm 1 == brute-force cover sum, Prop. 1 recursion == Algorithm 1 restarted, "
      f"Eq. (sampling) vs true chain: max abs error {worst:.1e} over 200 strings x 6 bytes: "
      f"{'pass' if ok4 else 'FAIL'}")
ok &= ok4
print("ALL CHECKS PASS" if ok else "CHECK FAILED")
sys.exit(0 if ok else 1)
