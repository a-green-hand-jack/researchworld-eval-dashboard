"""Prints the numbers quoted in the paper text (for verification against results/*.csv)."""
import os
import numpy as np
import pandas as pd
pd.set_option("display.width", 250); pd.set_option("display.max_columns", 30); pd.set_option("display.max_rows", 200)
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")
real = pd.read_csv(f"{R}/real_summary.csv"); syn = pd.read_csv(f"{R}/synth_summary.csv")
rp = real.pivot_table(index=["dataset", "n"], columns="method", values="ratio_vs_ppipp")
sp = syn[syn.N == 10000].pivot_table(index=["scenario", "n"], columns="method", values="ratio_vs_ppipp")
print("== synth t-corrected NC-spline vs ppi++ (ref pkg), no-gain scenarios")
print(sp.loc[(["herm0", "binaryf", "logistic1"], [50, 100]), ["ppi++_own", "spline4", "spline4_t", "ppi++_own_t"]].round(3))
print("== lognorm1.5 / lognorm1")
print(sp.loc[(["lognorm1", "lognorm1.5"], [200, 1000]), ["spline4", "spline6", "cf_iso"]].round(3))
th = syn[(syn.N == 10000) & (syn.method == "spline4")].set_index(["scenario", "n"]).theory_ratio_eff
print(th.loc[(["lognorm1", "lognorm1.5"], [200, 1000])].round(3))
print("== real: spline4 / ppi++_own (ratio of mean ratios)")
x = (rp["spline4"] / rp["ppi++_own"]).unstack("n"); print(x.round(4))
print("== real: strat, cf_iso at n=200, 2000")
print(rp[["strat_ppi5", "cf_iso", "ppi++_own", "spline4"]].loc[(slice(None), [200, 1000, 2000]), :].round(3))
print("== real mean coverage n>=500 by method")
print(real[real.n >= 500].groupby("method").cover.mean().round(4))
print("== real mean coverage n<=100 by method")
print(real[real.n <= 100].groupby("method").cover.mean().round(4))
print("== synth t-vs-nonT worst coverage")
print(syn[syn.N == 10000].groupby("method").cover.min().round(3))
print("== real: classical/ppi++ width at n=200")
print(rp["classical"].xs(200, level="n").round(3))
d = pd.read_csv(f"{R}/distort_summary.csv")
dp = d.pivot_table(index=["transform", "dataset", "n"], columns="method", values="ratio_vs_ppipp")
print("== distort: spline4/own"); print((dp["spline4"] / dp["ppi++_own"]).round(3).unstack("n"))
print("== distort coverage min/mean spline4:", d[d.method == "spline4"].cover.min(), d[d.method == "spline4"].cover.mean())
print("== distort spline4_t coverage", d[d.method == "spline4_t"].cover.min())
print("== N sweep (n=200)")
ns = syn[(syn.n == 200) & syn.scenario.isin(["herm60", "lognorm1", "logistic3"])].pivot_table(index=["scenario", "N"], columns="method", values="ratio_vs_ppipp")
print(ns[["ppi++_own", "spline4", "cf_iso"]].round(3))
print(syn[(syn.n == 200) & syn.scenario.isin(["herm60", "lognorm1", "logistic3"]) & (syn.method == "spline4")][["scenario", "N", "theory_ratio", "theory_ratio_eff", "cover"]].round(3))
