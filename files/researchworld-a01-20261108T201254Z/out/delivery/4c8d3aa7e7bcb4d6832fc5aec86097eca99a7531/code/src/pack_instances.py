"""Pack / unpack the per-instance result CSVs so the code/ delivery can reproduce the analysis offline.
Usage: python3 src/pack_instances.py pack     results/*.csv -> results/instances/*.csv.gz (gzip -9, mtime 0: deterministic)
       python3 src/pack_instances.py unpack   results/instances/*.csv.gz -> results/*.csv (existing files are kept)
Not packed: ollb_powmeans_weighted.csv (131 MB; regenerated by `make job_ollb_powmeans`, ~4 CPU-min) and theory_pairs.csv (regenerated by `make theory`)."""
import gzip, pathlib, shutil, sys
R = pathlib.Path(__file__).resolve().parents[1] / "results"; D = R / "instances"
SKIP = {"ollb_powmeans_weighted.csv", "theory_pairs.csv"}
if sys.argv[1:] == ["pack"]:
    D.mkdir(exist_ok=True)
    for p in sorted(R.glob("*.csv")):
        if p.name in SKIP: continue
        with open(p, "rb") as f, open(D / (p.name + ".gz"), "wb") as raw, gzip.GzipFile(filename="", mode="wb", fileobj=raw, compresslevel=9, mtime=0) as g:
            shutil.copyfileobj(f, g)
        print("packed", p.name)
elif sys.argv[1:] == ["unpack"]:
    for p in sorted(D.glob("*.csv.gz")):
        out = R / p.name[:-3]
        if out.exists(): print("kept", out.name); continue
        with gzip.open(p, "rb") as f, open(out, "wb") as o: shutil.copyfileobj(f, o)
        print("unpacked", out.name)
else: sys.exit(__doc__)
