"""Render LaTeX numeric macros and concise tables from measured analysis only."""
import json
import math
from pathlib import Path

import pandas as pd

ROOT=Path(__file__).resolve().parent
A=ROOT/'analysis'


def main():
    c=json.loads((A/'contrasts.json').read_text());g=pd.read_csv(A/'groups.csv');t=json.loads((A/'timing.json').read_text())
    m={}
    def put(name,x,fmt='.2f'):m[name]=format(float(x),fmt)
    def interval(prefix,obj,fmt='.2f',exponent=False):
        for k,suffix in [('mean',''),('lo','Lo'),('hi','Hi')]:put(prefix+suffix,math.exp(obj[k]) if exponent else obj[k],fmt)
    interval('WD',c['width']['D']);interval('WRelative',c['width']['D'],exponent=True)
    interval('WTrain',c['width']['train_log_effect'],exponent=True);interval('WGen',c['width']['eval_log_effect'],exponent=True,fmt='.3f')
    put('WPadj',c['width']['p_holm'],'.4f')
    interval('WNinetyFive',c['width95']['D']);interval('WNinety',c['width90']['D'])
    wide=next(x for x in c['secondary_width_grid'] if x['low_width']==64 and x['high_width']==256)
    interval('WideD',wide['D'],'.3f')
    for h,prefix in [(32,'Small'),(128,'Large')]:
        obj=c['clock'+str(h)]
        interval('K'+prefix,obj['K'],'.3f');put('K'+prefix+'P',obj['p_holm'],'.2f')
        interval('Clock'+prefix+'RestrictedRatio',obj['ratio_of_restricted_means'],'.3f')
        if 'uncensored_log_clock_ratio' in obj:interval('Clock'+prefix+'Ratio',obj['uncensored_log_clock_ratio'],'.3f',True)
    interval('NormMeanD',c['normalizations']['mean']['D']);interval('NormMatchedD',c['normalizations']['matched']['D'])
    put('CPUHours',t['sum_cpu_hours'],'.2f');put('RunSecondsMin',t['min_run_wall'],'.1f');put('RunSecondsMax',t['max_run_wall'],'.1f')
    execution=json.loads((ROOT/'confirm_jobs.json.execution.json').read_text())
    put('ElapsedMinutes',execution['total_wall']/60,'.1f')
    stable=pd.read_csv(A/'stability_groups.csv')
    half=stable[(stable.tag=='decay')&(stable.width==128)&(stable.decay==.05)].iloc[0]
    put('HalfLargeFinalMean',100*half.final_mean,'.1f');put('HalfLargeFinalMin',100*half.final_min,'.1f')
    put('HalfLargeFinalEvents',half.final99,'.0f');put('HalfLargeRegressions',8-half.final99,'.0f')
    for tag,h,prefix in [('main',8,'MainTiny'),('main',16,'MainNarrow'),('main',32,'MainSmall'),('main',128,'MainLarge'),
                         ('capacitytrain',1024,'CapacityTrain'),('capacityfrozen',1024,'CapacityFrozen'),
                         ('frozen',128,'FrozenLarge'),('shuffle',128,'ShuffleLarge')]:
        row=g[(g.tag==tag)&(g.width==h)].iloc[0]
        for metric,short in [('final_train_acc','Train'),('final_eval_acc','Eval')]:
            obj={k:100*row[metric+'_'+k] for k in ['mean','lo','hi']};interval(prefix+short,obj,'.1f')
        put(prefix+'TrainEvents',row.t_train_events,'.0f');put(prefix+'EvalEvents',row.t_eval_events,'.0f')
        put(prefix+'IncLo',100*row.t_eval_wilson_lo,'.1f');put(prefix+'IncHi',100*row.t_eval_wilson_hi,'.1f')
    (A/'numbers.tex').write_text('% Generated by export_tex.py from actual saved outputs.\n'+'\n'.join('\\newcommand{\\'+k+'}{'+v+'}' for k,v in m.items())+'\n')
    lines=[]
    for key,label in [('width','W: width32 to128'),('clock32','C: width32'),('clock128','C: width128')]:
        obj=c[key];q=obj.get('D',obj.get('K'))
        lines.append(f"{label} & {q['mean']:.3f} [{q['lo']:.3f}, {q['hi']:.3f}] & {obj['p']:.5f} & {obj['p_holm']:.5f} \\\\")
    (A/'primary_table.tex').write_text('\n'.join(lines)+'\n')
    print('Generated numbers.tex and primary_table.tex')

if __name__=='__main__':main()
