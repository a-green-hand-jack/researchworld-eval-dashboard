import json
import re
from pathlib import Path

import jsonschema
import pymupdf


def main():
    root = Path(__file__).resolve().parents[1]
    manifest = json.loads((root / 'figure_manifest.json').read_text())
    schema = json.loads((root / '.codex/skills/validate-paper/templates/figure_manifest.schema.json').read_text())
    jsonschema.validate(manifest, schema)
    strategy = json.loads((root / 'paper_strategy.json').read_text())
    for specification in strategy['figure_specs']:
        entry = next(item for item in manifest['figures'] if item['figure_id'] == specification['figure_id'])
        assert entry['n_panels'] <= specification['max_panels']
        assert entry['panels_per_row'] <= specification['max_panels_per_row']
        assert max(entry['categories_per_panel']) <= specification['max_categories_per_panel']
        assert max(entry['series_per_panel']) <= specification['max_series_per_panel']
        for key in ['path_pdf', 'path_png', 'prompt_log_path']:
            if key in entry:
                assert (root / entry[key]).is_file()
    pointer_checks = 0
    # @evidence[[paper.tex]]
    for target, locator in re.findall(r'@evidence\[\[([^\]#]+)#([^\]]+)\]\]', (root / 'paper.tex').read_text()):
        artifact = root / target
        assert artifact.is_file(), target
        if locator.startswith('/'):
            value = json.loads(artifact.read_text())
            for token in locator[1:].split('/'):
                token = token.replace('~1', '/').replace('~0', '~')
                value = value[int(token)] if isinstance(value, list) else value[token]
            pointer_checks += 1
        elif re.fullmatch(r'L\d+', locator):
            assert int(locator[1:]) <= len(artifact.read_text().splitlines())
    tex = (root / 'paper.tex').read_text()
    for row in (root / 'supplementary_rows.tex').read_text().splitlines():
        assert row in tex
    pdf = pymupdf.open(root / 'paper.pdf')
    references_page = next(page.number for page in pdf if re.search(r'(?m)^REFERENCES\s*$', page.get_text()))
    supplementary_page = next(page.number for page in pdf if re.search(r'(?m)^SUPPLEMENTARY INFORMATION\s*$', page.get_text()))
    assert 8 <= references_page <= 9
    assert supplementary_page > references_page
    forbidden = r'\b(?:idea|ideas|program|programs|attempt|attempts|eligible|worker_01|worker_02|combined_score|rubric)\b'
    for page in pdf:
        text = page.get_text()
        text = re.sub(r'source_evidence/downstream/\s*program/src/program\.py', '', text)
        text = re.sub(r'program/src/program\.py', '', text)
        text = re.sub(r'program\.\s*py', '', text)
        assert not re.search(forbidden, text, re.I), (page.number, re.findall(forbidden, text, re.I))
    last_body = pdf[references_page - 1]
    bounds = [span['bbox'] for block in last_body.get_text('dict')['blocks'] if block['type'] == 0 for line in block['lines'] for span in line['spans'] if span['text'].strip() and not span['text'].strip().isdigit() and span['text'] != 'Generated by The Agentic Scientist' and span['bbox'][0] >= 106 and span['bbox'][2] <= 506 and span['bbox'][1] >= 80 and span['bbox'][3] <= 750]
    report = dict(status='local_checks_passed_host_checks_pending', body_pages=references_page, total_pdf_pages=len(pdf), supplementary_starts_page=supplementary_page + 1, checked_json_pointers=pointer_checks, last_body_content_bounds=[min(bound[1] for bound in bounds), max(bound[3] for bound in bounds)], last_body_vertical_span_fraction=(max(bound[3] for bound in bounds) - 84) / 648, notes=['Geometric body bounds use rendered PDF text, excluding the line ruler, page number and watermark; host venue validation remains authoritative.', 'Canonical figure wrapper cannot import the absent host src.orchestrator package. Canonical JSON Schema and declared density budgets pass locally.', 'Canonical compile-input wrapper rejects the system TeX config symlink from /usr/share/texmf to /usr/share/texlive, both system roots. No validator or system symlink was modified.', 'The concept overview is the expressly permitted self-guarded placeholder; the orchestrator must render it before publication.'])
    (root / 'local_validation_report.json').write_text(json.dumps(report, indent=2) + '\n')
    (root / 'local_validation_report.json.prov.json').write_text(json.dumps({'schema_name': 'scientific-evidence.artifact-manifest', 'artifact': {'path': 'local_validation_report.json', 'kind': 'derived'}, 'derived_from': ['@evidence[[paper.pdf]]', '@evidence[[paper.tex]]', '@evidence[[figure_manifest.json]]', '@evidence[[paper_strategy.json]]'], 'generated_by': {'script_path': 'scripts/check_artifacts.py'}}, indent=2) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
