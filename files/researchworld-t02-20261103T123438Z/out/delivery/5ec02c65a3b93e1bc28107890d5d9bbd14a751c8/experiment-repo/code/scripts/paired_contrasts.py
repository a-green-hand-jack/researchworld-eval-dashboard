"""Paired width contrasts; resample entire seed pairs, retain non-events."""
import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'src'))
from events import bootstrap_mean

parser = argparse.ArgumentParser()
parser.add_argument('runs',help='runs.json generated by analyze.py')
parser.add_argument('--low-width',type=int,required=True)
parser.add_argument('--high-width',type=int,required=True)
parser.add_argument('--output',required=True)
args = parser.parse_args()
runs = json.loads(Path(args.runs).read_text())
strata_keys = ['p','task','fraction','activation','lr','weight_decay','steps','eval_every','onset_horizon','split_rule','frozen_hidden']
strata = defaultdict(lambda: defaultdict(dict))
for r in runs:
    if r['width'] not in [args.low_width,args.high_width]:
        continue
    stratum = tuple(r[k] for k in strata_keys)
    seed = (r['split_seed'],r['init_seed'])
    if r['width'] in strata[stratum][seed]:
        raise ValueError(f'Duplicate run {stratum}, {seed}, width {r["width"]}')
    strata[stratum][seed][r['width']] = r
metrics = ['restricted_train_time','restricted_valid_time','restricted_waiting_time',
           'final_train_acc','final_valid_acc','final_valid_loss','final_spectral_fraction']
contrasts = []
for stratum, seed_runs in strata.items():
    paired = {k:v for k,v in seed_runs.items() if len(v)==2}
    missing = [k for k,v in seed_runs.items() if len(v)!=2]
    row = dict(zip(strata_keys,stratum))
    row.update(low_width=args.low_width,high_width=args.high_width,n_pairs=len(paired),
               missing_pairs=missing,direction='high width minus low width',
               seed_pairs=list(paired),matched_split_hashes=all(
                   r[args.low_width]['split_sha256']==r[args.high_width]['split_sha256'] for r in paired.values()))
    if not row['matched_split_hashes']:
        raise ValueError('Seed-paired runs do not have matching train/validation splits')
    if paired:
        for metric in metrics:
            differences = [r[args.high_width][metric]-r[args.low_width][metric]
                           for r in paired.values() if r[args.high_width][metric] is not None
                           and r[args.low_width][metric] is not None]
            row[metric] = bootstrap_mean(differences) if len(differences)==len(paired) else None
        for event in ['train_event','valid_event']:
            differences = [int(r[args.high_width][event]['observed'])-int(r[args.low_width][event]['observed'])
                           for r in paired.values()]
            row[event+'_probability_difference'] = bootstrap_mean(differences)
    contrasts.append(row)
Path(args.output).write_text(json.dumps(contrasts,indent=2)+'\n')
print(f'Wrote {len(contrasts)} strata; pairing uses split and initialization seeds')
