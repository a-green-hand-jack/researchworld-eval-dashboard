"""results/FAM/{curves,paired}.csv -> results/FAM/TABLES.md (headline RMSE at k=3/8/20 and the P1/P7/X1/X2 rows per regime).
python3 exp/fam_tables.py   (run exp/analyze_fam.py first)"""
import os, pandas as pd
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
c = pd.read_csv('results/FAM/curves.csv'); p = pd.read_csv('results/FAM/paired.csv')
out = ['# Family-aware headline results (generated by exp/fam_tables.py)\n',
       'RMSE (same units as Table 2, mean over held-out models) with 95% CI. `model` = bootstrap over held-out models, `family` = bootstrap over organisations.',
       'main = random folds; famfold = family-held-out folds; famfoldx = famfold without the family that carries >30% of the mean-predictor MSE.\n']
for m in ['A1', 'A2', 'B']:
    out.append(f'\n## {m}: RMSE\n\n| regime | selector | k=3 | k=8 | k=20 |\n|---|---|---|---|---|')
    q = c[c.matrix == m]
    for r in ['main_model', 'main_family', 'famfold_model', 'famfold_family', 'famfoldx_model', 'famfoldx_family']:
        for s in ['random', 'greedyA', 'greedyAcomp', 'fwdreg', 'cluster']:
            z = q[(q.regime == r) & (q.selector == s)].set_index('k')
            if len(z) == 3:
                out.append(f'| {r} | {s} | ' + ' | '.join(f'{z.est[k]:.3f} [{z.lo[k]:.3f}, {z.hi[k]:.3f}]' for k in (3, 8, 20)) + ' |')
    out.append(f'\n## {m}: paired comparisons (rel = difference / mean MSE of the second selector; negative = first better; 95% CI of rel, bootstrap of the MSE difference divided by the same denominator, the full-sample mean MSE of the second selector; an interval end below -1 can occur because the denominator is fixed while the MSE of the second selector varies across resamples, it does not mean an error reduced by more than 100%; `identical selections` = both selectors chose the same benchmarks)\n')
    out.append('| regime | test | status | k | rel | CI of rel | p | p_holm (family size) |\n|---|---|---|---|---|---|---|---|')
    for r in ['main_model', 'main_family', 'famfold_model', 'famfold_family', 'famfoldx_model', 'famfoldx_family']:
        for _, w in p[(p.matrix == m) & (p.regime == r)].iterrows():
            den = w['diff'] / w.rel if abs(w.rel) > 1e-12 else float('nan')
            if den != den:  # identical selections: the difference is exactly 0, no test
                out.append(f'| {r} | {w.test} | {w.status} | {w.k} | 0 (identical selections) | - | - | - |')
                continue
            out.append(f'| {r} | {w.test} | {w.status} | {w.k} | {w.rel:+.3f} | [{w.lo / den:+.3f}, {w.hi / den:+.3f}] | {w.p:.4f} | {w.p_holm:.3f} ({int(w.holm_family)}) |')
open('results/FAM/TABLES.md', 'w').write('\n'.join(out) + '\n')
