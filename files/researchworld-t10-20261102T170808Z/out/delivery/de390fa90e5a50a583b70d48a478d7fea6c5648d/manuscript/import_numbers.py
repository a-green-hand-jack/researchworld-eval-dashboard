#!/usr/bin/env python3
"""Format existing analysis summaries for manuscript prose; performs no inference."""
from pathlib import Path
import csv, hashlib, json
root=Path(__file__).resolve().parent.parent
summ=list(csv.DictReader((root/'results/summary.csv').open()))
pairs=list(csv.DictReader((root/'results/paired.csv').open()))
lines=['% Generated by manuscript/import_numbers.py from delivered analysis outputs.']
def macro(k,v): lines.append('\\newcommand{\\'+k+'}{'+str(v)+'}')
def one(rows,**keys):
 found=[r for r in rows if all(str(r[k])==str(v) for k,v in keys.items())]
 if len(found)!=1: raise ValueError((keys,len(found)))
 return found[0]
def uncertainty(x):
 value=f'{float(x):.2g}'
 if 'e' in value:
  coefficient,exponent=value.split('e')
  return r'\ensuremath{'+coefficient+r'\times10^{'+str(int(exponent))+'}}'
 return value

def cell(prefix,scenario,n,N,method='cf_cubic',baseline='ppi++'):
 r=one(summ,scenario=scenario,n=n,N=N,method=method)
 macro(prefix+'Coverage',f"{float(r['coverage']):.4f}")
 macro(prefix+'CoverageCI',f"[{float(r['coverage_lo']):.4f}, {float(r['coverage_hi']):.4f}]")
 macro(prefix+'Hits',r['hits']);macro(prefix+'Width',f"{float(r['mean_width']):.5f}")
 macro(prefix+'WidthSE',uncertainty(r['width_mcse']))
 if baseline:
  p=one(pairs,scenario=scenario,n=n,N=N,method=method,baseline=baseline)
  macro(prefix+'Ratio',f"{float(p['width_ratio']):.4f}")
  macro(prefix+'RatioCI',f"[{float(p['ratio_lo']):.4f}, {float(p['ratio_hi']):.4f}]")
  macro(prefix+'Reduction',f"{100*(1-float(p['width_ratio'])):.1f}\\%")
for args in [
 ('Quad','quadratic',2000,20000),('Linear','linear',2000,20000),('NoSignal','no_signal',2000,20000),
 ('Galaxy','galaxies',2000,20000),('Forest','forest',2000,20000),('AlphaFold','alphafold',2000,20000),
 ('Rare','rare_binary',100,1000),('RareLabel','rare_binary',100,1000,'label',None),
 ('RareExact','rare_binary',100,1000,'clopper_pearson',None),
 ('Bounded','bounded_quadratic',10000,100000,'eb_cubic','eb_label'),
 ('BoundedSmall','bounded_quadratic',2000,20000,'eb_cubic','eb_label'),
 ('BoundedUnit','bounded_quadratic',10000,100000,'eb_cubic','eb_ppi_full'),
 ('BoundedScalar','bounded_quadratic',10000,100000,'eb_cubic','eb_scalar'),
 ('QuadEqual','quadratic',2000,2000),
 ('QuadUnclipped','quadratic',2000,20000,'cf_cubic','scalar_unclipped'),
 ('QuadBase','quadratic',2000,20000,'ppi++',None)]:cell(*args)
for group,prefix in [('synthetic','Synthetic'),('real','Real'),('bounded','BoundedRun'),('ratio1','RatioRun')]:
 meta=json.loads((root/'results'/group/'metadata.json').read_text());macro(prefix+'Seconds',f"{meta['elapsed_seconds']:.1f}")
(root/'manuscript/numbers.tex').write_text('\n'.join(lines)+'\n')
(root/'manuscript/number-sources.json').write_text(json.dumps({
 'generator':'manuscript/import_numbers.py',
 'inputs':{str(p.relative_to(root)):hashlib.sha256(p.read_bytes()).hexdigest() for p in [root/'results/summary.csv',root/'results/paired.csv']}
},indent=2)+'\n')
